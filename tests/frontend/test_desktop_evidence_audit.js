'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const path = require('node:path');
const sandbox = {window: {}};
vm.createContext(sandbox);
vm.runInContext(fs.readFileSync(path.resolve(__dirname, '../../frontend/forensic-explorer.js'), 'utf8'), sandbox);
const explorer = new sandbox.window.ForensicExplorer({});
const unknown = explorer.renderFindingsTab([{type: 'FACT', epistemic_state: 'UNVERIFIED', statement: '<script>bad</script>'}]);
assert(unknown.includes('>UNVERIFIED</span>'));
assert(!unknown.includes('fe-badge-green'));
assert(!unknown.includes('<script>'));
assert(explorer.renderFindingsTab([{type: 'FACT', epistemic_state: 'SUPPORTED'}]).includes('fe-badge-green'));
const nodes = [];
const parent = {prepend: node => nodes.push(node), querySelector: () => null};
const doc = {createElement: () => ({dataset: {}, setAttribute() {}, innerHTML: ''})};
const context = {window: {}, document: doc};
vm.createContext(context);
vm.runInContext(fs.readFileSync(path.resolve(__dirname, '../../frontend/unified-report-renderer.js'), 'utf8'), context);
const mount = {innerHTML: '', parentElement: parent, querySelectorAll: () => []};
context.window.renderUnifiedReport(mount, {evidence_workbench: {schema: 'evidence-workbench-v1',
  passages: [{text: 'Exact captured words.', evidence_id: 'source-1', published_at: '2026-10-28', start: 0, end: 21}]}});
assert(nodes.some(n => n.innerHTML.includes('3 quoted words across all passage pages')));
assert(mount.innerHTML.includes('Capture and attribution details'));
assert(mount.innerHTML.includes('2026-10-28'));
assert(mount.innerHTML.includes('Exact captured words.'));
assert(!mount.innerHTML.includes('<details class="ur-capture-details" open'));
console.log('DESKTOP EVIDENCE AUDIT PASSED');
